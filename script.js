document.addEventListener("DOMContentLoaded", () => {
  const root = document.documentElement;
  const menuToggle = document.getElementById("menuToggle");
  const navLinks = document.getElementById("navLinks");
  const languageToggle = document.getElementById("languageToggle");
  const themeToggle = document.getElementById("themeToggle");
  const paletteSelect = document.getElementById("paletteSelect");
  let language = localStorage.getItem("portfolio-language") === "en" ? "en" : "es";

  const applyLanguage = (nextLanguage) => {
    language = nextLanguage;
    root.lang = language;
    document.title = language === "es"
      ? "Edgar Sánchez | Técnico en Desarrollo de Software"
      : "Edgar Sánchez | Software Development Technician";
    document.querySelector('meta[name="description"]').content = language === "es"
      ? "Portafolio de Edgar Sánchez, técnico en desarrollo de software y electrónica industrial en Guatemala."
      : "Portfolio of Edgar Sánchez, software development and industrial electronics technician in Guatemala.";

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const translation = translations[language][element.dataset.i18n];
      if (translation) element.textContent = translation;
    });

    document.querySelector(".portrait-image").alt = language === "es"
      ? "Fotografía de Edgar Sánchez"
      : "Photo of Edgar Sánchez";
    document.querySelector(".portrait-card").setAttribute(
      "aria-label",
      language === "es" ? "Fotografía de Edgar Sánchez" : "Photo of Edgar Sánchez"
    );
    languageToggle.textContent = language === "es" ? "EN" : "ES";
    languageToggle.setAttribute(
      "aria-label",
      language === "es" ? "Change language to English" : "Cambiar idioma a español"
    );
    paletteSelect.setAttribute(
      "aria-label",
      language === "es" ? "Color de acento" : "Accent color"
    );
    menuToggle.setAttribute(
      "aria-label",
      language === "es" ? "Abrir menú de navegación" : "Open navigation menu"
    );
    localStorage.setItem("portfolio-language", language);
  };

  const applyTheme = (theme) => {
    root.dataset.theme = theme;
    const targetTheme = theme === "dark" ? "light" : "dark";
    const label = language === "es"
      ? (targetTheme === "light" ? "Cambiar a modo claro" : "Cambiar a modo oscuro")
      : (targetTheme === "light" ? "Switch to light mode" : "Switch to dark mode");
    themeToggle.setAttribute("aria-label", label);
    themeToggle.title = label;
    document.querySelector('meta[name="theme-color"]').content =
      theme === "dark" ? "#0b1220" : "#f4f7fb";
    localStorage.setItem("portfolio-theme", theme);
  };

  const savedPalette = localStorage.getItem("portfolio-palette");
  const validPalettes = ["blue", "emerald", "violet", "amber"];
  const initialPalette = validPalettes.includes(savedPalette) ? savedPalette : "blue";
  const initialTheme = localStorage.getItem("portfolio-theme") === "light" ? "light" : "dark";
  root.dataset.palette = initialPalette;
  paletteSelect.value = initialPalette;
  document.getElementById("currentYear").textContent = new Date().getFullYear();

  applyLanguage(language);
  applyTheme(initialTheme);

  languageToggle.addEventListener("click", () => {
    applyLanguage(language === "es" ? "en" : "es");
    applyTheme(root.dataset.theme);
  });

  themeToggle.addEventListener("click", () => {
    applyTheme(root.dataset.theme === "dark" ? "light" : "dark");
  });

  paletteSelect.addEventListener("change", () => {
    root.dataset.palette = paletteSelect.value;
    localStorage.setItem("portfolio-palette", paletteSelect.value);
  });

  menuToggle.addEventListener("click", () => {
    const isOpen = navLinks.classList.toggle("active");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
    menuToggle.setAttribute(
      "aria-label",
      isOpen
        ? (language === "es" ? "Cerrar menú de navegación" : "Close navigation menu")
        : (language === "es" ? "Abrir menú de navegación" : "Open navigation menu")
    );
  });

  navLinks.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      navLinks.classList.remove("active");
      menuToggle.setAttribute("aria-expanded", "false");
    });
  });

  const revealElements = document.querySelectorAll(".reveal");
  if ("IntersectionObserver" in window) {
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12 });
    revealElements.forEach((element) => revealObserver.observe(element));
  } else {
    revealElements.forEach((element) => element.classList.add("visible"));
  }
});
